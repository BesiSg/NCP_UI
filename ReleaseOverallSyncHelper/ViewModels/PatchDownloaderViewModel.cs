        private Task ImportData()
        {
            return Task.Run(() =>
            {
                //CanImportData = false;
                var htmlcontent = _atlassianWiki.GetPageContentAsync(392268702).Result;
                var dict = WikiParser.ParseCustomerTableDict(htmlcontent);
                foreach (var kvp in dict)
                {
                    _custAbbre.Get.Update(kvp.Value, kvp.Key);
                }
                var tags = _ncpBitBucketHandler.GetTagsOnRepository("release_overall").Result;
                var releasestags = tags.Values.Where(x =>
                    Regex.IsMatch(
                    x.displayId,
                    @"^R(?<Version>\d+\.\d+\.\d+)$",
                    RegexOptions.IgnoreCase));
                var updatebranches = UpdateDats();
                var tasks = new List<Task>();
                foreach (var tag in releasestags)
                {
                    tasks.Add(Task.Run(() =>
                    {
                        var content = _ncpBitBucketHandler.GetReleaseOverAllContent(
                            tag.latestCommit).Result;

                        var unitversions = _unitVersionParser.PopulateUnitSelections(
                            tag.displayId,
                            content);

                        lock (_storage.Get.Storage)
                        {
                            _storage.Get.Replace(unitversions, tag.displayId);
                        }
                    }));
                }
                Task.WhenAll(tasks).Wait();
                updatebranches.Wait();
                //CanImportData = true;
            });
        }

        private async Task UpdateDats()
        {
            var semaphore = new SemaphoreSlim(3); // max 3 concurrent repos

            var tasks = Enum.GetValues<NCPBitbucket.Repository>()
            .Select(async repo =>
            {
                await semaphore.WaitAsync();

                try
                {
                    var branchresult = await _BBBranchHandler.GetAllAsync($"NCP {repo}");
                    Message = branchresult.ErrorMessage + "\n\r";
                }
                catch(Exception ex)
                {
                    Message += $"{repo} encountered {ex.Message}" + "\n\r";
                }
                finally
                {
                    semaphore.Release();
                }
            });
            await Task.WhenAll(tasks);
            tasks = Enum.GetValues<NCPBitbucket.Repository>()
                .Select(async repo =>
                {
                    await semaphore.WaitAsync();

                    try
                    {
                        var tagresult = await _BBTagHandler.GetAllAsync($"NCP {repo}");
                        Message = tagresult.ErrorMessage + "\n\r";
                    }
                    catch (Exception ex)
                    {
                        Message += $"{repo} encountered {ex.Message}" + "\n\r";
                    }
                    finally
                    {
                        semaphore.Release();
                    }
                });
            await Task.WhenAll(tasks);
        }
        private bool DoesTagExist(string repo, string tag)
        {
            var key = $"NCP {repo}";
            if (!_tagDat.Get.Storage.ContainsKey(key)) return false;
            return _tagDat.Get.Storage[key].Any(t =>
                string.Equals(
                    t.displayId,
                    tag));
        }
        private string GetNextTag(string repo, string version, string customer, string revision)
        {
            var key = $"NCP {repo}";
            var orderedlist = _tagDat.Get.Storage[key].Where(x => x.displayId.Contains($"{version}.{customer}", StringComparison.CurrentCultureIgnoreCase)).OrderBy(x => x.displayId, new NaturalSortComparer());
            var lasttag = orderedlist.LastOrDefault();
            if (lasttag == null)
                return $"{version}.{customer}1";

            var match = Regex.Match(lasttag.displayId, @"(\d+)$");

            int nextRev = match.Success
            ? int.Parse(match.Groups[1].Value) + 1
            : 1;

            return $"{version}.{customer}{nextRev}";
        }
