        private async Task<string> CloneRepo(string version, string unit, string path, CancellationToken cancellationToken)
        {
            if (!unit.TryToEnumByAttribute<NCPBitbucket.Repository>(out var repo))
                return "Fail to parse string to Repository enum";
            var msg = await _ncpBitBucketHandler.Clone("NCP", version, repo, path, true, cancellationToken);
            if (string.IsNullOrEmpty(Message))
                Message = string.Empty;
            lock (Message)
            {
                return Message += msg;
            }
        }
